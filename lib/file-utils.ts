/**
 * HomeNest Core File Utilities
 * Centralized file url resolution, size formatting, and MIME/extension checkers.
 */

import { config } from '@/lib/config';

/**
 * Resolves a file URL (absolute or relative to backend URL)
 */
export function resolveFileUrl(url?: string | null): string {
  if (!url) return '';
  if (
    url.startsWith('http://') ||
    url.startsWith('https://') ||
    url.startsWith('data:') ||
    url.startsWith('blob:')
  ) {
    return url;
  }
  const base = config.backendUrl || '';
  return `${base}/${url.replace(/^\//, '')}`;
}

/**
 * Formats file size in bytes to human-readable string (B, KB, MB, GB)
 */
export function formatFileSize(size?: number | string | null): string {
  if (size === undefined || size === null || size === '') return '';
  if (typeof size === 'string') {
    const trimmed = size.trim();
    if (/^[0-9]+(\.[0-9]+)?\s*(B|KB|MB|GB|TB)$/i.test(trimmed)) {
      return trimmed;
    }
  }
  const num = typeof size === 'string' ? parseFloat(size) : size;
  if (isNaN(num)) return String(size);
  if (num < 1024) return `${Math.round(num)} B`;
  if (num < 1024 * 1024) return `${(num / 1024).toFixed(1)} KB`;
  return `${(num / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * Checks whether the file is an image by extension or URL
 */
export function isImageFile(fileName?: string, url?: string): boolean {
  const target = (fileName || url || '').toLowerCase();
  return /\.(png|jpe?g|webp|gif|svg|bmp|ico)(\?.*)?$/i.test(target);
}

/**
 * Checks whether the file is a PDF by extension or URL
 */
export function isPdfFile(fileName?: string, url?: string): boolean {
  const target = (fileName || url || '').toLowerCase();
  return /\.pdf(\?.*)?$/i.test(target);
}

/**
 * Checks whether the file is a video by extension, MIME type, or is_video flag
 */
export function isVideoFile(
  fileName?: string,
  url?: string,
  mimeType?: string,
  isVideo?: boolean
): boolean {
  if (isVideo === true) return true;
  if (mimeType && mimeType.toLowerCase().startsWith('video/')) return true;
  const target = (fileName || url || '').toLowerCase();
  return /\.(mp4|webm|ogg|mov|m4v|mkv|avi|3gp|flv)(\?.*)?$/i.test(target);
}

/**
 * Extracts clean uppercase file extension (e.g. PNG, PDF) from file name or URL
 */
export function getFileExtension(fileName?: string, url?: string): string {
  const target = (fileName || url || '').trim();
  const match = target.match(/\.([a-zA-Z0-9]+)(\?.*)?$/);
  return match ? match[1].toUpperCase() : 'FILE';
}

/**
 * Returns human-friendly label for attachments instead of raw timestamp hashes
 */
export function getAttachmentDisplayName(fileName?: string, index?: number): string {
  if (!fileName || !fileName.trim()) {
    return `Attachment ${(index ?? 0) + 1}`;
  }

  const clean = fileName.trim();

  // Pattern: complaint-1795069191081-772813617.png or upload-123456789.jpg
  const autoGeneratedPattern = /^(complaint|upload|attachment|file|doc)[-_]\d+[-_]\d+(\.[a-zA-Z0-9]+)?$/i;
  const matchExt = clean.match(/\.([a-zA-Z0-9]+)$/);
  const ext = matchExt ? matchExt[1].toUpperCase() : '';

  if (autoGeneratedPattern.test(clean)) {
    const typeLabel = ['PNG', 'JPG', 'JPEG', 'WEBP', 'GIF', 'SVG'].includes(ext)
      ? 'Screenshot'
      : ['MP4', 'WEBM', 'MOV', 'M4V', 'MKV', 'OGG', 'AVI', '3GP'].includes(ext)
      ? 'Video'
      : ext === 'PDF'
      ? 'Document'
      : 'Attachment';
    return `${typeLabel} ${(index ?? 0) + 1}`;
  }

  // If filename is very long (e.g. > 24 chars), truncate cleanly while keeping extension
  if (clean.length > 24 && matchExt) {
    const baseName = clean.slice(0, clean.lastIndexOf('.'));
    return `${baseName.slice(0, 16)}...${matchExt[0]}`;
  }

  return clean;
}
