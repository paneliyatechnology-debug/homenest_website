/**
 * Resolves a file URL (absolute or relative to backend URL)
 */
export function resolveFileUrl(url?: string | null): string {
  if (!url) return '';
  if (
    url.startsWith('http://') ||
    url.startsWith('https://') ||
    url.startsWith('data:') ||
    url.startsWith('blob:')
  ) {
    return url;
  }
  const base = config.backendUrl || '';
  return `${base}/${url.replace(/^\//, '')}`;
}

/**
 * Formats file size in bytes to human-readable string (B, KB, MB)
 */
export function formatFileSize(size?: number | string | null): string {
  if (size === undefined || size === null || size === '') return '';
  if (typeof size === 'string') {
    const trimmed = size.trim();
    if (/^[0-9]+(\.[0-9]+)?\s*(B|KB|MB|GB|TB)$/i.test(trimmed)) {
      return trimmed;
    }
  }
  const num = typeof size === 'string' ? parseFloat(size) : size;
  if (isNaN(num)) return String(size);
  if (num < 1024) return `${Math.round(num)} B`;
  if (num < 1024 * 1024) return `${(num / 1024).toFixed(1)} KB`;
  return `${(num / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * Checks whether the file is an image by extension/URL
 */
export function isImageFile(fileName?: string, url?: string): boolean {
  const target = (fileName || url || '').toLowerCase();
  return /\.(png|jpe?g|webp|gif|svg|bmp|ico)(\?.*)?$/i.test(target);
}

/**
 * Checks whether the file is a PDF
 */
export function isPdfFile(fileName?: string, url?: string): boolean {
  const target = (fileName || url || '').toLowerCase();
  return /\.pdf(\?.*)?$/i.test(target);
}

/**
 * Extracts clean uppercase file extension (e.g. PNG, PDF)
 */
export function getFileExtension(fileName?: string, url?: string): string {
  const target = (fileName || url || '').trim();
  const match = target.match(/\.([a-zA-Z0-9]+)(\?.*)?$/);
  return match ? match[1].toUpperCase() : 'FILE';
}

/**
 * Returns human-friendly label for attachments instead of raw timestamp hashes
 */
export function getAttachmentDisplayName(fileName?: string, index?: number): string {
  if (!fileName || !fileName.trim()) {
    return `Attachment ${(index ?? 0) + 1}`;
  }

  const clean = fileName.trim();

  // Pattern: complaint-1795069191081-772813617.png or upload-123456789.jpg
  const autoGeneratedPattern = /^(complaint|upload|attachment|file)[-_]\d+[-_]\d+(\.[a-zA-Z0-9]+)?$/i;
  const matchExt = clean.match(/\.([a-zA-Z0-9]+)$/);
  const ext = matchExt ? matchExt[1].toUpperCase() : '';

  if (autoGeneratedPattern.test(clean)) {
    const typeLabel = ['PNG', 'JPG', 'JPEG', 'WEBP', 'GIF', 'SVG'].includes(ext)
      ? 'Screenshot'
      : ext === 'PDF'
      ? 'Document'
      : 'Attachment';
    return `${typeLabel} ${(index ?? 0) + 1}`;
  }

  // If filename is very long (e.g. > 24 chars), truncate cleanly while keeping extension
  if (clean.length > 24 && matchExt) {
    const baseName = clean.slice(0, clean.lastIndexOf('.'));
    return `${baseName.slice(0, 16)}...${matchExt[0]}`;
  }

  return clean;
}

interface PdfPreviewViewerProps {
  fileUrl: string;
  fileName: string;
}

/**
 * Isolated PDF Preview Viewer that loads the PDF as a same-origin Blob
 * to avoid cross-origin / iframe sandbox blocking across ports (3000 -> 5000).
 */
const PdfPreviewViewer: React.FC<PdfPreviewViewerProps> = ({ fileUrl, fileName }) => {
  const [pdfBlobUrl, setPdfBlobUrl] = useState<string | null>(null);
  const [pdfLoading, setPdfLoading] = useState<boolean>(true);
  const [pdfError, setPdfError] = useState<boolean>(false);

  useEffect(() => {
    const controller = new AbortController();
    let createdUrl: string | null = null;

    fetch(fileUrl, { signal: controller.signal })
      .then((res) => {
        if (!res.ok) throw new Error(`HTTP error! status: ${res.status}`);
        return res.blob();
      })
      .then((blob) => {
        const pdfBlob = new Blob([blob], { type: 'application/pdf' });
        createdUrl = URL.createObjectURL(pdfBlob);
        setPdfBlobUrl(createdUrl);
        setPdfLoading(false);
      })
      .catch((err) => {
        if (controller.signal.aborted) return;
        console.warn('PDF fetch for preview failed, falling back to direct URL:', err);
        setPdfError(true);
        setPdfLoading(false);
      });

    return () => {
      controller.abort();
      if (createdUrl) {
        URL.revokeObjectURL(createdUrl);
      }
    };
  }, [fileUrl]);

  if (pdfError) {
    return (
      <div className="flex flex-col items-center justify-center py-12 px-6 text-center text-white space-y-4">
        <div className="w-16 h-16 rounded-2xl bg-white/10 flex items-center justify-center text-rose-400">
          <i className="pi pi-file-pdf text-3xl" />
        </div>
        <div>
          <h4 className="text-sm sm:text-base font-bold text-white">{fileName}</h4>
          <p className="text-xs text-gray-400 mt-1">Unable to display PDF preview inline in this browser.</p>
        </div>
        <div className="flex items-center gap-3">
          <a
            href={fileUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-2 px-4 py-2 bg-white/10 hover:bg-white/20 text-white rounded-xl text-xs font-semibold transition-colors"
          >
            <i className="pi pi-external-link text-xs" />
            <span>Open in New Tab</span>
          </a>
          <a
            href={fileUrl}
            download={fileName}
            className="inline-flex items-center gap-2 px-4 py-2 bg-[#175C46] hover:bg-[#124b38] text-white rounded-xl text-xs font-semibold shadow-md transition-colors"
          >
            <i className="pi pi-download text-xs" />
            <span>Download PDF</span>
          </a>
        </div>
      </div>
    );
  }

  return (
    <div className="w-full h-[66vh] relative flex items-center justify-center bg-gray-900 rounded-xl overflow-hidden shadow-2xl">
      {pdfLoading && (
        <div className="absolute inset-0 z-10 flex flex-col items-center justify-center bg-gray-950/80 text-white gap-2 backdrop-blur-xs">
          <div className="w-8 h-8 border-2 border-emerald-500 border-t-transparent rounded-full animate-spin" />
          <span className="text-xs text-gray-300 font-medium">Loading PDF document...</span>
        </div>
      )}
      <object
        data={pdfBlobUrl || fileUrl}
        type="application/pdf"
        className="w-full h-full rounded-xl bg-white"
      >
        <iframe
          src={pdfBlobUrl || fileUrl}
          title={fileName}
          className="w-full h-full rounded-xl border-0 bg-white"
        />
      </object>
    </div>
  );
};

interface AttachmentPreviewContentProps {
  onHide: () => void;
  attachments: ComplaintAttachment[];
  initialIndex: number;
}

const AttachmentPreviewContent: React.FC<AttachmentPreviewContentProps> = ({
  onHide,
  attachments,
  initialIndex,
}) => {
  const [currentIndex, setCurrentIndex] = useState<number>(() => {
    return initialIndex >= 0 && initialIndex < attachments.length ? initialIndex : 0;
  });
  const [zoom, setZoom] = useState<number>(1);
  const [rotation, setRotation] = useState<number>(0);

  const hasMultiple = attachments.length > 1;
  const current = attachments[currentIndex] || attachments[0] || null;

  const fileName =
    current?.name || current?.file_name || `attachment_${currentIndex + 1}.png`;
  const rawUrl = current?.url || current?.file_url || '';
  const fileUrl = resolveFileUrl(rawUrl);
  const fileSize = formatFileSize(current?.size || current?.file_size);
  const isImage = isImageFile(fileName, fileUrl);
  const isPdf = isPdfFile(fileName, fileUrl);
  const ext = getFileExtension(fileName, fileUrl);

  const handlePrev = () => {
    setZoom(1);
    setRotation(0);
    setCurrentIndex((prev) => (prev > 0 ? prev - 1 : attachments.length - 1));
  };

  const handleNext = () => {
    setZoom(1);
    setRotation(0);
    setCurrentIndex((prev) => (prev < attachments.length - 1 ? prev + 1 : 0));
  };

  const handleSelectIndex = (idx: number) => {
    setZoom(1);
    setRotation(0);
    setCurrentIndex(idx);
  };

  // Keyboard navigation
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'ArrowLeft') {
        e.preventDefault();
        setZoom(1);
        setRotation(0);
        setCurrentIndex((prev) => (prev > 0 ? prev - 1 : attachments.length - 1));
      } else if (e.key === 'ArrowRight') {
        e.preventDefault();
        setZoom(1);
        setRotation(0);
        setCurrentIndex((prev) => (prev < attachments.length - 1 ? prev + 1 : 0));
      } else if (e.key === 'Escape') {
        e.preventDefault();
        onHide();
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [attachments.length, onHide]);

  const zoomIn = () => setZoom((z) => Math.min(3, +(z + 0.25).toFixed(2)));
  const zoomOut = () => setZoom((z) => Math.max(0.5, +(z - 0.25).toFixed(2)));
  const resetZoom = () => {
    setZoom(1);
    setRotation(0);
  };
  const rotateRight = () => setRotation((r) => (r + 90) % 360);

  if (!current) {
    return null;
  }

  return (
    <div className="flex flex-col">
      {/* Header Bar */}
      <div className="p-4 sm:p-5 border-b border-gray-100 flex items-center justify-between gap-3 bg-white">
        {/* File Title & Meta */}
        <div className="flex items-center gap-2.5 min-w-0">
          <div className="w-9 h-9 rounded-xl bg-[#E8F8F0] text-[#175C46] flex items-center justify-center shrink-0">
            <i
              className={
                isImage
                  ? 'pi pi-image text-sm'
                  : isPdf
                  ? 'pi pi-file-pdf text-rose-500 text-sm'
                  : 'pi pi-file text-sm'
              }
            />
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-2 flex-wrap">
              <h3
                className="text-sm font-bold text-gray-900 truncate max-w-[260px] sm:max-w-[420px]"
                title={fileName}
              >
                {fileName}
              </h3>
              {hasMultiple && (
                <span className="text-[11px] font-semibold text-[#175C46] bg-[#E8F8F0] px-2 py-0.5 rounded-full shrink-0">
                  {currentIndex + 1} / {attachments.length}
                </span>
              )}
            </div>
            <div className="flex items-center gap-2 mt-0.5">
              <span className="text-[9px] font-bold uppercase tracking-wider px-1.5 py-0.5 rounded bg-gray-100 text-gray-600">
                {ext}
              </span>
              {fileSize && (
                <span className="text-[11px] text-gray-400">{fileSize}</span>
              )}
            </div>
          </div>
        </div>

        {/* Quick Action Toolbar */}
        <div className="flex items-center gap-1 sm:gap-1.5 shrink-0">
          {isImage && (
            <>
              <button
                type="button"
                onClick={zoomOut}
                disabled={zoom <= 0.5}
                className="w-8 h-8 flex items-center justify-center text-gray-600 hover:text-gray-900 hover:bg-gray-100 rounded-lg transition-colors cursor-pointer disabled:opacity-30 disabled:cursor-not-allowed"
                title="Zoom Out"
                aria-label="Zoom Out"
              >
                <svg className="w-4 h-4 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
                  <path strokeLinecap="round" strokeLinejoin="round" d="M21 21l-5.197-5.197m0 0A7.5 7.5 0 105.196 5.196a7.5 7.5 0 0010.607 10.607zM13 10H7" />
                </svg>
              </button>
              <span className="text-[11px] font-semibold text-gray-500 px-1 min-w-[36px] text-center select-none">
                {Math.round(zoom * 100)}%
              </span>
              <button
                type="button"
                onClick={zoomIn}
                disabled={zoom >= 3}
                className="w-8 h-8 flex items-center justify-center text-gray-600 hover:text-gray-900 hover:bg-gray-100 rounded-lg transition-colors cursor-pointer disabled:opacity-30 disabled:cursor-not-allowed"
                title="Zoom In"
                aria-label="Zoom In"
              >
                <svg className="w-4 h-4 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
                  <path strokeLinecap="round" strokeLinejoin="round" d="M21 21l-5.197-5.197m0 0A7.5 7.5 0 105.196 5.196a7.5 7.5 0 0010.607 10.607zM10 7v6m3-3H7" />
                </svg>
              </button>
              <button
                type="button"
                onClick={rotateRight}
                className="w-8 h-8 flex items-center justify-center text-gray-600 hover:text-gray-900 hover:bg-gray-100 rounded-lg transition-colors cursor-pointer"
                title="Rotate 90°"
                aria-label="Rotate 90 degrees"
              >
                <svg className="w-4 h-4 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
                  <path strokeLinecap="round" strokeLinejoin="round" d="M16.023 9.348h4.992v-.001M2.985 19.644v-4.992m0 0h4.992m-4.993 0l3.181 3.183a8.25 8.25 0 0013.803-3.7M4.031 9.865a8.25 8.25 0 0113.803-3.7l3.181 3.182m0-4.991v4.99" />
                </svg>
              </button>
              {(zoom !== 1 || rotation !== 0) && (
                <button
                  type="button"
                  onClick={resetZoom}
                  className="px-2 py-1 text-[11px] font-semibold text-gray-600 hover:text-gray-900 hover:bg-gray-100 rounded-lg transition-colors cursor-pointer"
                  title="Reset Zoom & Rotation"
                >
                  Reset
                </button>
              )}
              <div className="w-[1px] h-5 bg-gray-200 mx-1" />
            </>
          )}

          {fileUrl && (
            <>
              <a
                href={fileUrl}
                target="_blank"
                rel="noopener noreferrer"
                className="p-1.5 text-gray-600 hover:text-[#175C46] hover:bg-gray-100 rounded-lg transition-colors cursor-pointer"
                title="Open original in new tab"
                aria-label="Open original in new tab"
              >
                <svg className="w-4 h-4 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
                  <path strokeLinecap="round" strokeLinejoin="round" d="M13.5 6H5.25A2.25 2.25 0 003 8.25v10.5A2.25 2.25 0 005.25 21h10.5A2.25 2.25 0 0018 18.75V10.5m-10.5 6L21 3m0 0h-5.25M21 3v5.25" />
                </svg>
              </a>
              <a
                href={fileUrl}
                download={fileName}
                target="_blank"
                rel="noopener noreferrer"
                className="p-1.5 text-gray-600 hover:text-[#175C46] hover:bg-gray-100 rounded-lg transition-colors cursor-pointer"
                title="Download file"
                aria-label="Download file"
              >
                <svg className="w-4 h-4 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
                  <path strokeLinecap="round" strokeLinejoin="round" d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-4l-4 4m0 0l-4-4m4 4V4" />
                </svg>
              </a>
            </>
          )}

          <div className="w-[1px] h-5 bg-gray-200 mx-1" />

          {/* Close button */}
          <button
            type="button"
            onClick={onHide}
            className="w-8 h-8 flex items-center justify-center text-gray-400 hover:text-gray-700 hover:bg-gray-100 rounded-lg transition-colors cursor-pointer"
            title="Close Preview"
            aria-label="Close Preview"
          >
            <svg className="w-5 h-5 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2">
              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>
      </div>

      {/* Main Preview Canvas */}
      <div className="p-4 sm:p-6 bg-gray-50/60">
        <div className="relative min-h-[380px] max-h-[70vh] flex items-center justify-center overflow-hidden bg-gray-950/95 rounded-2xl shadow-inner p-3 sm:p-5 select-none">
          {/* Previous Arrow Button */}
          {hasMultiple && (
            <button
              type="button"
              onClick={handlePrev}
              className="absolute left-3 top-1/2 -translate-y-1/2 z-20 w-10 h-10 rounded-full bg-black/60 hover:bg-black/90 text-white flex items-center justify-center transition-all backdrop-blur-xs cursor-pointer shadow-lg hover:scale-105 active:scale-95"
              title="Previous (Left arrow key)"
              aria-label="Previous attachment"
            >
              <svg className="w-5 h-5 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2.5">
                <path strokeLinecap="round" strokeLinejoin="round" d="M15 19l-7-7 7-7" />
              </svg>
            </button>
          )}

          {/* Next Arrow Button */}
          {hasMultiple && (
            <button
              type="button"
              onClick={handleNext}
              className="absolute right-3 top-1/2 -translate-y-1/2 z-20 w-10 h-10 rounded-full bg-black/60 hover:bg-black/90 text-white flex items-center justify-center transition-all backdrop-blur-xs cursor-pointer shadow-lg hover:scale-105 active:scale-95"
              title="Next (Right arrow key)"
              aria-label="Next attachment"
            >
              <svg className="w-5 h-5 stroke-current" fill="none" viewBox="0 0 24 24" strokeWidth="2.5">
                <path strokeLinecap="round" strokeLinejoin="round" d="M9 5l7 7-7 7" />
              </svg>
            </button>
          )}

          {/* Preview Content */}
          {isImage ? (
            <div className="w-full h-full max-h-[66vh] flex items-center justify-center overflow-auto custom-scrollbar">
              <img
                src={fileUrl}
                alt={fileName}
                style={{
                  transform: `scale(${zoom}) rotate(${rotation}deg)`,
                  transition: 'transform 0.2s cubic-bezier(0.16, 1, 0.3, 1)',
                }}
                className="max-h-[64vh] max-w-full w-auto h-auto object-contain rounded-lg shadow-2xl transition-all"
                loading="eager"
              />
            </div>
          ) : isPdf ? (
            <PdfPreviewViewer key={fileUrl} fileUrl={fileUrl} fileName={fileName} />
          ) : (
            <div className="flex flex-col items-center justify-center py-16 px-6 text-center text-white space-y-4">
              <div className="w-16 h-16 rounded-2xl bg-white/10 flex items-center justify-center text-emerald-400">
                <i className="pi pi-file text-3xl" />
              </div>
              <div>
                <h4 className="text-sm sm:text-base font-bold text-white">{fileName}</h4>
                <p className="text-xs text-gray-400 mt-1">{fileSize || 'Binary document'}</p>
              </div>
              {fileUrl && (
                <a
                  href={fileUrl}
                  download={fileName}
                  className="inline-flex items-center gap-2 px-5 py-2.5 bg-[#175C46] hover:bg-[#124b38] text-white rounded-xl text-xs font-semibold shadow-md transition-colors"
                >
                  <i className="pi pi-download text-xs" />
                  <span>Download file to view</span>
                </a>
              )}
            </div>
          )}
        </div>

        {/* Thumbnail Carousel for fast multi-file navigation */}
        {hasMultiple && (
          <div className="pt-3 flex items-center justify-center gap-2.5 overflow-x-auto py-1 custom-scrollbar">
            {attachments.map((attItem, idx) => {
              const itemFileName =
                attItem.name || attItem.file_name || `attachment_${idx + 1}`;
              const itemUrl = resolveFileUrl(attItem.url || attItem.file_url);
              const itemIsImage = isImageFile(itemFileName, itemUrl);
              const isActive = idx === currentIndex;

              return (
                <button
                  key={idx}
                  type="button"
                  onClick={() => handleSelectIndex(idx)}
                  className={`w-13 h-13 rounded-xl overflow-hidden border-2 transition-all cursor-pointer shrink-0 relative bg-gray-100 flex items-center justify-center ${
                    isActive
                      ? 'border-[#175C46] ring-2 ring-emerald-300 scale-105 shadow-xs'
                      : 'border-gray-200/80 opacity-60 hover:opacity-100 hover:border-gray-300'
                  }`}
                  title={itemFileName}
                >
                  {itemIsImage ? (
                    <img
                      src={itemUrl}
                      alt=""
                      className="w-full h-full object-cover"
                      loading="lazy"
                    />
                  ) : (
                    <div className="w-full h-full bg-[#E8F8F0] text-[#175C46] flex items-center justify-center">
                      <i className="pi pi-file text-sm" />
                    </div>
                  )}
                  {isActive && (
                    <div className="absolute inset-0 bg-[#175C46]/10 pointer-events-none" />
                  )}
                </button>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
};

